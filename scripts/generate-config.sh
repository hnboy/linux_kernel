enable() {
    local opt="$1"
    if grep -q "^# $opt is not set" "$CONFIG"; then
        sed -i "s/^# $opt is not set/$opt=y/" "$CONFIG"
    elif ! grep -q "^$opt=" "$CONFIG"; then
        echo "$opt=y" >> "$CONFIG"
    fi
}

disable() {
    local opt="$1"
    if grep -q "^$opt=y" "$CONFIG"; then
        sed -i "s/^$opt=y/# $opt is not set/" "$CONFIG"
    elif ! grep -q "^# $opt is not set" "$CONFIG"; then
        echo "# $opt is not set" >> "$CONFIG"
    fi
}

set_value() {
    local opt="$1" val="$2"
    if grep -q "^$opt=" "$CONFIG"; then
        sed -i "s/^$opt=.*/$opt=$val/" "$CONFIG"
    elif grep -q "^# $opt is not set" "$CONFIG"; then
        sed -i "s/^# $opt is not set/$opt=$val/" "$CONFIG"
    else
        echo "$opt=$val" >> "$CONFIG"
    fi
